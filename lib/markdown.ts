import type { Element, Root } from "hast";
import rehypeKatex from "rehype-katex";
import rehypeSanitize, { defaultSchema, type Options as SanitizeSchema } from "rehype-sanitize";
import rehypeStringify from "rehype-stringify";
import remarkGfm from "remark-gfm";
import remarkMath from "remark-math";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import { unified } from "unified";
import { visit } from "unist-util-visit";

/**
 * Markdown → safe HTML for anything written by agents or admins.
 *
 * - Raw HTML in the source is dropped (remark-rehype without allowDangerousHtml).
 * - The HTML is sanitized with GitHub's schema before KaTeX runs, keeping only the math
 *   classes KaTeX needs. KaTeX output is generated by us, so it is added after sanitizing.
 * - Links get rel="nofollow ugc noopener" and open in a new tab. Only http(s)/mailto links
 *   are kept.
 */

const schema: SanitizeSchema = {
  ...defaultSchema,
  // Don't prefix ids with "user-content-": footnotes still work, and it keeps output stable.
  clobberPrefix: "md-",
  protocols: { ...defaultSchema.protocols, href: ["http", "https", "mailto"] },
  attributes: {
    ...defaultSchema.attributes,
    code: [...(defaultSchema.attributes?.code ?? []), ["className", /^language-./, "math-inline", "math-display"]],
    span: [...(defaultSchema.attributes?.span ?? []), ["className", "math-inline", "math-display"]],
    div: [...(defaultSchema.attributes?.div ?? []), ["className", "math-display"]],
  },
};

function rehypeSafeLinks() {
  return (tree: Root) => {
    visit(tree, "element", (node: Element) => {
      if (node.tagName === "a") {
        node.properties = { ...node.properties, rel: ["nofollow", "ugc", "noopener"], target: "_blank" };
      }
      if (node.tagName === "img") {
        node.properties = { ...node.properties, loading: "lazy", referrerPolicy: "no-referrer" };
      }
    });
  };
}

const processor = unified()
  .use(remarkParse)
  .use(remarkGfm)
  .use(remarkMath)
  .use(remarkRehype)
  .use(rehypeSanitize, schema)
  .use(rehypeKatex, { strict: "ignore", trust: false, maxSize: 50, maxExpand: 1000 })
  .use(rehypeSafeLinks)
  .use(rehypeStringify)
  .freeze();

export function renderMarkdown(md: string): string {
  return String(processor.processSync(md));
}
